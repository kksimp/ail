#!/usr/bin/env python3
"""Untested spec rules (ADR 0463). Measurement only (ADR 0070).

A rule counts as tested when its id appears in a file that tests it: a case in
tests/cases/ or tests/*/ (as .rules, .err, .trap or inside the
program), an example, a compiler test, or a spec block the spec suite runs
(an `ail` fence with `rules=` or `error=` that is not `norun` or `skip`). Ranges like
`err.prop.1-4` count every id they span. Prints a table by chapter and, with
--list, every untested id. Exit 0 always: this reports, the lanes fix.

    tools/coverage/rules.py            # table by chapter
    tools/coverage/rules.py --list     # + the ids
    tools/coverage/rules.py --md FILE  # write docs/design/rule-coverage.md
"""
import os, re, sys, time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFINE = re.compile(r"^\*\*([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+)\*\*", re.M)
MENTION = re.compile(r"\b([a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+)\.(\d+)(?:[-–](\d+))?")
TEST_DIRS = ["tests", "examples", "compiler", "tools/fuzz"]
TEXT_EXT = {".ail", ".rules", ".err", ".trap", ".rs", ".out", ".test", ".stderr", ".expected", ".md", ".sh", ".txt"}


def defined():
    rules = {}
    d = os.path.join(ROOT, "docs", "spec")
    for f in sorted(os.listdir(d)):
        if not f.endswith(".md") or f == "README.md":
            continue
        for m in DEFINE.finditer(open(os.path.join(d, f), encoding="utf-8").read()):
            rules[m.group(1)] = f
    return rules


FENCE = re.compile(r"^```ail([^\n]*)$", re.M)
ATTR = re.compile(r"\b(?:rules|error)=([^\s]+)")


def spec_blocks():
    """Rule ids cited by `rules=`/`error=` on spec fences the suite runs."""
    seen = set()
    d = os.path.join(ROOT, "docs", "spec")
    for f in os.listdir(d):
        if not f.endswith(".md"):
            continue
        for m in FENCE.finditer(open(os.path.join(d, f), encoding="utf-8").read()):
            info = m.group(1)
            if "norun" in info or "skip" in info:
                continue
            for a in ATTR.finditer(info):
                for r in a.group(1).split(","):
                    for mm in MENTION.finditer(r):
                        lo = int(mm.group(2))
                        hi = int(mm.group(3)) if mm.group(3) else lo
                        for n in range(lo, min(hi, lo + 40) + 1):
                            seen.add("%s.%d" % (mm.group(1), n))
    return seen


def tested():
    seen = spec_blocks()
    for top in TEST_DIRS:
        for dp, dn, fn in os.walk(os.path.join(ROOT, top)):
            dn[:] = [x for x in dn if x not in ("target", "failures", "tmp")]
            for f in fn:
                if os.path.splitext(f)[1] not in TEXT_EXT:
                    continue
                try:
                    text = open(os.path.join(dp, f), encoding="utf-8", errors="ignore").read()
                except OSError:
                    continue
                for m in MENTION.finditer(text):
                    lo = int(m.group(2))
                    hi = int(m.group(3)) if m.group(3) else lo
                    for n in range(lo, min(hi, lo + 40) + 1):
                        seen.add("%s.%d" % (m.group(1), n))
    return seen


def main():
    rules, seen = defined(), tested()
    by = {}
    for r, f in rules.items():
        t = by.setdefault(f, [0, []])
        if r in seen:
            t[0] += 1
        else:
            t[1].append(r)
    total = len(rules)
    hit_all = sum(v[0] for v in by.values())
    lines = ["%-22s %6s %7s %5s" % ("chapter", "rules", "tested", "pct")]
    for f in sorted(by):
        hit, miss = by[f]
        n = hit + len(miss)
        lines.append("%-22s %6d %7d %4d%%" % (f, n, hit, 100 * hit // max(n, 1)))
    lines.append("%-22s %6d %7d %4d%%" % ("all", total, hit_all, 100 * hit_all // max(total, 1)))
    print("\n".join(lines))
    if "--list" in sys.argv or "--md" in sys.argv:
        for f in sorted(by):
            if by[f][1]:
                print("\n%s: %s" % (f, " ".join(sorted(by[f][1]))))
    if "--md" in sys.argv:
        path = sys.argv[sys.argv.index("--md") + 1]
        out = ["# Rule coverage", "", "Generated by `tools/coverage/rules.py` (ADR 0463) on %s." % time.strftime("%Y-%m-%d", time.gmtime()),
               "A rule is tested when its id appears in a case, example or compiler test, or in a spec block the spec suite runs (`rules=` or `error=`). Rules tagged `[definitional]` describe the language and need no code. Untested rules are filed to the owning lane.", "",
               "| chapter | rules | tested | % |", "|---|---:|---:|---:|"]
        for f in sorted(by):
            hit, miss = by[f]
            n = hit + len(miss)
            out.append("| %s | %d | %d | %d%% |" % (f, n, hit, 100 * hit // max(n, 1)))
        out.append("| **all** | %d | %d | %d%% |" % (total, hit_all, 100 * hit_all // max(total, 1)))
        out += ["", "## Untested rules", ""]
        for f in sorted(by):
            if by[f][1]:
                out.append("- **%s** (%d): %s" % (f, len(by[f][1]), " ".join("`%s`" % r for r in sorted(by[f][1]))))
        full = os.path.join(ROOT, path) if not os.path.isabs(path) else path
        tail = ""
        if os.path.exists(full):  # keep hand-written sections after the table
            old = open(full, encoding="utf-8").read()
            i = old.find("\n## Documentation snippets")
            tail = old[i:] if i >= 0 else ""
        open(full, "w").write("\n".join(out) + "\n" + tail)


if __name__ == "__main__":
    main()
