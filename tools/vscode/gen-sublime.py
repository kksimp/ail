#!/usr/bin/env python3
"""Writes syntaxes/ail.sublime-syntax from syntaxes/ail.tmLanguage.json (the one source of truth).

    python3 gen-sublime.py          write the file
    python3 gen-sublime.py --check  fail if the file is out of date
"""
import json, sys, pathlib
import yaml

HERE = pathlib.Path(__file__).parent
SRC = HERE / "syntaxes" / "ail.tmLanguage.json"
OUT = HERE / "syntaxes" / "ail.sublime-syntax"


def caps(c):
    return {int(k): v["name"] for k, v in c.items() if "name" in v} or None


def rule(r):
    if "include" in r:
        return {"include": r["include"].lstrip("#")}
    if "match" in r:
        d = {"match": r["match"]}
        if "name" in r:
            d["scope"] = r["name"]
        c = caps(r.get("captures", {}))
        if c:
            d["captures"] = c
        return d
    # begin/end: push an anonymous context; the end rule comes first (TextMate priority)
    body = []
    if "name" in r:
        body.append({"meta_scope": r["name"]})
    if "contentName" in r:
        body.append({"meta_content_scope": r["contentName"]})
    end = {"match": r["end"], "pop": True}
    c = caps(r.get("endCaptures", {}))
    if c:
        end["captures"] = c
    body.append(end)
    body += [rule(p) for p in r.get("patterns", [])]
    d = {"match": r["begin"]}
    c = caps(r.get("beginCaptures", {}))
    if c:
        d["captures"] = c
    d["push"] = body
    return d


def build():
    g = json.loads(SRC.read_text())
    ctx = {"main": [rule(p) for p in g["patterns"]]}
    for name, r in g["repository"].items():
        ctx[name] = [rule(p) for p in r["patterns"]] if "patterns" in r and "begin" not in r else [rule(r)]
    doc = {"name": g["name"], "scope": g["scopeName"], "file_extensions": ["ail"], "contexts": ctx}
    head = ("%YAML 1.2\n---\n# Generated by gen-sublime.py from ail.tmLanguage.json. Do not edit by hand.\n")
    return head + yaml.dump(doc, sort_keys=False, default_flow_style=False, width=1000, allow_unicode=True)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "ail.sublime-syntax is out of date: run python3 tools/vscode/gen-sublime.py")
    OUT.write_text(text)
