#!/usr/bin/env python3
"""Writes compiler/rt/native/brotli_data.ail: the fixed data of a Brotli
decoder (RFC 7932, std.compress.12, ADR 1241).

    python3 tools/native/gen_brotli.py BROTLI_DIR > compiler/rt/native/brotli_data.ail

BROTLI_DIR is a checkout of https://github.com/google/brotli (MIT licence).
It reads three files there, which hold the RFC's appendices as data:
`c/common/dictionary.bin` (Appendix A, the static dictionary, checked against
the RFC's SHA-256), `c/common/transform.c` (Appendix B, the 121 word
transforms) and `c/common/context.c` (section 7.1, the context lookup
tables). The dictionary is stored DEFLATE-compressed and base64-encoded
(77 KB of text instead of 164 KB), and the runtime inflates it once per
process with `cz_inflate` (compress.ail).
"""

import base64
import codecs
import hashlib
import re
import sys
import zlib

DICT_SHA256 = "20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70"
CHUNK = 4000  # base64 characters per constant, a multiple of 4


def c_array(text, name):
    m = re.search(name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    out = []
    for tok in body.replace("\n", " ").split(","):
        tok = tok.strip()
        if tok:
            out.append(tok)
    return out


def main():
    root = sys.argv[1]
    data = open(f"{root}/c/common/dictionary.bin", "rb").read()
    if hashlib.sha256(data).hexdigest() != DICT_SHA256 or len(data) != 122784:
        sys.exit("dictionary.bin is not the RFC 7932 dictionary")
    tr = open(f"{root}/c/common/transform.c").read()
    ctx = open(f"{root}/c/common/context.c").read()

    m = re.search(r"kPrefixSuffix\[(\d+)\]\s*=\s*(.*?);", tr, re.S)
    lits = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))
    ps = codecs.decode("".join(lits), "unicode_escape").encode("latin-1") + b"\0"
    assert len(ps) == int(m.group(1))
    psmap = [int(x, 0) for x in c_array(tr, "kPrefixSuffixMap")]
    types = {}
    for k, v in re.findall(r"BROTLI_TRANSFORM_(\w+) = (\d+)", open(f"{root}/c/common/transform.h").read()):
        types[k] = int(v)
    tf = []
    for tok in c_array(tr, "kTransformsData"):
        tf.append(types[tok.replace("BROTLI_TRANSFORM_", "")] if tok.startswith("BROTLI_") else int(tok))
    assert len(tf) == 121 * 3 and max(tf) < 256
    lut = [int(x) for x in c_array(ctx, "_kBrotliContextLookupTable")]
    assert len(lut) == 2048

    packed = zlib.compress(data, 9)[2:-4]
    b64 = base64.b64encode(packed).decode()
    chunks = [b64[i:i + CHUNK] for i in range(0, len(b64), CHUNK)]

    w = sys.stdout.write
    w("## Runtime: part of the AIL native runtime; linked into user executables\n")
    w("## under the Runtime Exception (see LICENSE).\n")
    w("##\n")
    w("## Generated by tools/native/gen_brotli.py from the data of RFC 7932 as the\n")
    w("## Brotli project ships it (MIT licence, see NOTICE): std.compress.12,\n")
    w("## ADR 1241. Do not edit; run the generator.\n\n")
    w("## The prefix and suffix strings of the word transforms (Appendix B), each a\n")
    w("## length byte then its bytes, in hex.\n")
    w(f'BR_PS := "{ps.hex()}"\n\n')
    w("## Where each of the 50 prefix and suffix strings starts in BR_PS, in hex.\n")
    w(f'BR_PS_MAP := "{bytes(psmap).hex()}"\n\n')
    w("## The 121 transforms: prefix id, transform type, suffix id, in hex. Types:\n")
    w("## 0 identity, 1-9 omit the last 1-9 bytes, 10 uppercase first, 11 uppercase\n")
    w("## all, 12-20 omit the first 1-9 bytes.\n")
    w(f'BR_TF := "{bytes(tf).hex()}"\n\n')
    w("## The context lookup (section 7.1): 512 bytes per context mode (LSB6, MSB6,\n")
    w("## UTF8, signed), the last byte's 256 then the second last byte's, in hex.\n")
    w(f'BR_CTX := "{bytes(lut).hex()}"\n\n')
    w("## The static dictionary (Appendix A), 122784 bytes, DEFLATE-compressed and\n")
    w(f"## base64-encoded in {len(chunks)} parts.\n")
    w(f"BR_DICT_PARTS := {len(chunks)}\n\n")
    w("## Part `i` of the encoded dictionary.\n")
    w("fn br_dict_part(i int) str\n")
    for i, c in enumerate(chunks):
        w(f'    if i == {i}\n        return "{c}"\n')
    w('    ""\n')


main()
