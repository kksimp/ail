#!/usr/bin/env python3
"""Writes `compiler/rt/native/fmt_pow10.ail`: the 128-bit powers of ten that the
native runtime's float text uses (`fmt_flt.ail`, type.num.7, type.num.8):

    python3 tools/native/gen_pow10.py > compiler/rt/native/fmt_pow10.ail

Entry K, for K from -342 to 326, is 10^K scaled by a power of two into
[2^127, 2^128): T = 10^K * 2^(127 - floor(log2 10^K)), rounded down for
K >= 0 and up for K < 0 (the convention of the Eisel-Lemire method; the
shortest-digits method adds one for K >= 0 itself). It is the high word then
the low word, each as 16 letters `a` to `p` (a nibble each, least significant
first), so that a word decodes from two 8-byte loads without a branch. The
arithmetic is exact (Python integers and fractions)."""

from fractions import Fraction

KMIN, KMAX = -342, 326


def entry(k):
    v = Fraction(10) ** k
    e = v.numerator.bit_length() - v.denominator.bit_length()
    if Fraction(2) ** e > v:
        e -= 1
    assert Fraction(2) ** e <= v < Fraction(2) ** (e + 1)
    t = v * Fraction(2) ** (127 - e)
    q = t.numerator // t.denominator
    if k < 0:
        q += 1
    assert 2 ** 127 <= q < 2 ** 128
    # The shortest-digits method adds one to the low word for K >= 0 and never
    # carries into the high word.
    assert k < 0 or (q & (2 ** 64 - 1)) != 2 ** 64 - 1
    return q


def word(x):
    return "".join(chr(97 + ((x >> (4 * i)) & 15)) for i in range(16))


def main():
    text = "".join(word(entry(k) >> 64) + word(entry(k) & (2 ** 64 - 1)) for k in range(KMIN, KMAX + 1))
    print("## Runtime: part of the AIL native runtime; linked into user executables")
    print("## under the Runtime Exception (see LICENSE).")
    print("##")
    print("## Generated by tools/native/gen_pow10.py (type.num.7, type.num.8). Do not")
    print("## edit; run the generator. Entry K (from FLT_KMIN) is 32 letters at")
    print("## 32 * (K - FLT_KMIN): 10^K in [2^127, 2^128), high word then low word.")
    print()
    print("FLT_KMIN := %d" % KMIN)
    print("FLT_KMAX := %d" % KMAX)
    print()
    print('FLT_POW10 := "%s"' % text)


main()
