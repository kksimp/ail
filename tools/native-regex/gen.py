#!/usr/bin/env python3
"""Random std.regex vectors for differential tests (lane 232).

    python3 tools/native-regex/gen.py N SEED > FILE

Writes N lines in the format of bootstrap/tests/regex/vectors.txt that
vectors.ail understands: search lines `PATTERN<TAB>TEXT<TAB>-`, and the
`ALL`, `REPLACE`, `REPLACE_FIRST`, `SPLIT` and `ERR` forms. The third column
of a search line is ignored by the harness (the engines are compared with
each other, not with an expectation). Patterns come from the std.regex.3
grammar, with a small share of malformed ones so the error kinds and their
offsets are compared too. Measurement tooling only (ADR 0070).
"""
import random
import sys

LIT = list("abcAB 1_-é")
CLASSES = [r"\d", r"\w", r"\s", r"\D", r"\W", r"\S", ".", r"[a-c]", r"[^a]", r"[[:alpha:]]", r"[[:^digit:]]",
           r"\pL", r"\p{Lu}", r"\PN", r"[\d_]", r"[a-cX-Z]", r"\x41", r"\x{e9}"]
ANCHORS = ["^", "$", r"\b", r"\B", r"\A", r"\z"]
FLAGS = ["(?i)", "(?s)", "(?m)", "(?i:", "(?-i)", "(?s:", "(?m:"]
BAD = ["(", ")", "[", "a{2,1}", "*a", "+", "?", r"\q", r"\1", "(?P<>a)", "(?P<n>a)(?P<n>b)", "[z-a]", r"\p{Nope}",
       "a{1001}", "(?z)", "(?<1a>x)", "[[:nope:]]", "a**", "(?i", r"\x{110000}"]
TEXT = list("abcABC 12_-\n\té.,")


def atom(rng, depth):
    r = rng.random()
    if r < 0.45:
        c = rng.choice(LIT)
        return c if c not in ".$^*+?()[]{}|\\" else "\\" + c
    if r < 0.70:
        return rng.choice(CLASSES)
    if r < 0.78:
        return rng.choice(ANCHORS)
    if depth > 3:
        return "a"
    kind = rng.random()
    inner = alt(rng, depth + 1)
    if kind < 0.45:
        return "(" + inner + ")"
    if kind < 0.7:
        return "(?:" + inner + ")"
    if kind < 0.85:
        return "(?P<n%d>%s)" % (rng.randint(0, 9), inner)
    f = rng.choice(FLAGS)
    return f + inner + ")" if f.endswith(":") else f + inner


def rep(rng, depth):
    a = atom(rng, depth)
    r = rng.random()
    if r < 0.5:
        return a
    q = rng.choice(["*", "+", "?", "{2}", "{1,3}", "{0,}", "{2,}"])
    if rng.random() < 0.3:
        q += "?"
    return a + q


def concat(rng, depth):
    return "".join(rep(rng, depth) for _ in range(rng.randint(1, 4)))


def alt(rng, depth):
    parts = [concat(rng, depth) for _ in range(rng.choice([1, 1, 1, 2, 3]))]
    return "|".join(parts)


def text(rng):
    return "".join(rng.choice(TEXT) for _ in range(rng.randint(0, 12)))


def esc(s):
    return s.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    rng = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
    out = ["# generated by tools/native-regex/gen.py"]
    for _ in range(n):
        pat = rng.choice(BAD) if rng.random() < 0.06 else alt(rng, 0)
        pat = pat.replace("\t", "\\t").replace("\n", "\\n")
        t = esc(text(rng))
        form = rng.random()
        if form < 0.45:
            out.append(f"{pat}\t{t}\t-")
        elif form < 0.65:
            out.append(f"ALL\t{pat}\t{t}\t-")
        elif form < 0.8:
            rep_t = rng.choice(["<$0>", "[${0}]", "$$", "x"])
            out.append(f"REPLACE\t{pat}\t{t}\t{rep_t}\t-")
        elif form < 0.88:
            rep_t = rng.choice(["<$0>", "$$", "x"])
            out.append(f"REPLACE_FIRST\t{pat}\t{t}\t{rep_t}\t-")
        elif form < 0.96:
            out.append(f"SPLIT\t{pat}\t{t}\t-")
        else:
            out.append(f"ERR\t{pat}\t-\t-")
    print("\n".join(out))


main()
