#!/usr/bin/env bash
# Self-compile status (lane 181, ADR 0585): lowers every compiler module to MIR
# with the native runtime and groups the native.subset.1 problems by file and by
# construct. Read-only: writes only to the directory given as $1 (default: a
# temp directory under the scratchpad or TMPDIR).
#
#   tools/self-compile/run.sh [OUT_DIR]
#
# Output: OUT_DIR/problems.tsv (file, line, col, rule, message) and
# OUT_DIR/summary.md (per file, and per construct with a count).
# Caveat: each file is lowered alone, so names defined in other modules can
# show up as extra problems until module loading lands (`use a.b`).
set -uo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
out="${1:-${TMPDIR:-/tmp}/self-compile-$$}"
mkdir -p "$out"
cd "$root" || exit 2

[ -x ./ail ] || { echo "run.sh: no ./ail launcher" >&2; exit 2; }

: > "$out/problems.tsv"
printf 'file\texit_code\n' > "$out/files.tsv"
find compiler -name '*.ail' ! -path 'compiler/rt/*' ! -name main.ail | sort | while read -r f; do
    ./ail run compiler mir "$f" compiler/rt/native > "$out/mir.out" 2>&1
    rc=$?
    grep -E '^[^ ]+:[0-9]+:[0-9]+: error\[' "$out/mir.out" |
        sed -E 's/^([^:]+):([0-9]+):([0-9]+): error\[([^]]+)\]: (.*)$/\1\t\2\t\3\t\4\t\5/' >> "$out/problems.tsv"
    printf '%s\t%s\n' "$f" "$rc" >> "$out/files.tsv"
done

{
    echo "# Self-compile status (generated by tools/self-compile/run.sh)"
    echo
    echo "## Problems per file"
    echo
    echo "| File | Count |"
    echo "|---|---|"
    cut -f1 "$out/problems.tsv" | sort | uniq -c | sort -rn | awk '{c=$1; $1=""; sub(/^ /,""); print "| " $0 " | " c " |"}'
    echo
    echo "## Problems per construct (names in back-quotes normalised to X)"
    echo
    echo "| Count | Construct |"
    echo "|---|---|"
    cut -f5 "$out/problems.tsv" | sed -E 's/`[^`]*`/`X`/g' | sort | uniq -c | sort -rn |
        awk '{c=$1; $1=""; sub(/^ /,""); print "| " c " | " $0 " |"}'
    echo
    echo "Total problems: $(wc -l < "$out/problems.tsv")"
} > "$out/summary.md"

cat "$out/summary.md"
