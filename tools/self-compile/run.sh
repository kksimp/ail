#!/usr/bin/env bash
# Self-compile status (lane 181, ADR 0585): builds the whole compiler with
# `ail build compiler/main.ail` (module loading, ADR 0393) and groups every
# native.subset.1 problem by file and by construct. Read-only apart from the
# output directory given as $1.
#
#   tools/self-compile/run.sh [OUT_DIR]
#
# Output: OUT_DIR/problems.tsv (file, line, col, rule, message) and
# OUT_DIR/summary.md (per file, and per construct with a count).
# Before module loading landed, the script lowered each module alone; that
# mode is in git history (ADR 0585 records why).
set -uo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
out="${1:-${TMPDIR:-/tmp}/self-compile-$$}"
mkdir -p "$out"
cd "$root" || exit 2
[ -x ./ail ] || { echo "run.sh: no ./ail launcher" >&2; exit 2; }

./ail build compiler/main.ail > "$out/build.out" 2>&1
build_rc=$?
grep -E '^[^ ]+:[0-9]+:[0-9]+: error\[' "$out/build.out" |
    sed -E 's/^([^:]+):([0-9]+):([0-9]+): error\[([^]]+)\]: (.*)$/\1\t\2\t\3\t\4\t\5/' > "$out/problems.tsv"

{
    echo "# Self-compile status (generated by tools/self-compile/run.sh)"
    echo
    echo "\`ail build compiler/main.ail\` exit code: $build_rc"
    echo
    echo "## Problems per file"
    echo
    echo "| Count | File |"
    echo "|---|---|"
    cut -f1 "$out/problems.tsv" | sort | uniq -c | sort -rn | awk '{c=$1; $1=""; sub(/^ /,""); print "| " c " | " $0 " |"}'
    echo
    echo "## Problems per construct (names in back-quotes normalised to X)"
    echo
    echo "| Count | Construct |"
    echo "|---|---|"
    cut -f5 "$out/problems.tsv" | sed -E 's/`[^`]*`/`X`/g' | sort | uniq -c | sort -rn |
        awk '{c=$1; $1=""; sub(/^ /,""); print "| " c " | " $0 " |"}'
    echo
    echo "Total problems: $(wc -l < "$out/problems.tsv")"
} > "$out/summary.md"

cat "$out/summary.md"
