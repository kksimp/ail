#!/usr/bin/env python3
"""Writes std/simd/simd.ail (ADR 1014). Run from the repository root:
python3 tools/simd/gen.py > std/simd/simd.ail"""

import re

# name, lane type, lanes, mask type, kind
TYPES = [
    ("F32x4", "f32", 4, "I32x4", "f32"),
    ("F64x2", "float", 2, "I64x2", "f64"),
    ("I32x4", "i32", 4, "I32x4", "i32"),
    ("I64x2", "int", 2, "I64x2", "i64"),
    ("F32x8", "f32", 8, "I32x8", "f32"),
    ("F64x4", "float", 4, "I64x4", "f64"),
    ("I32x8", "i32", 8, "I32x8", "i32"),
    ("I64x4", "int", 4, "I64x4", "i64"),
]

out = []


def split_top(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([":
            depth += 1
        if ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    return parts


def w(line):
    """Append a line; a constructor call over 100 columns is split one field a
    line, as `ail fmt` does (fmt.wrap)."""
    m = re.match(r"^    (\w+)\((l0: .*)\)$", line)
    if m and len(line) > 100:
        out.append("    {}(".format(m.group(1)))
        for part in split_top(m.group(2)):
            out.append("        {},".format(part))
        out.append("    )")
    else:
        out.append(line)


def lanes(n, f):
    return [f(i) for i in range(n)]


def build(name, n, f):
    return "{}({})".format(name, ", ".join("l{}: {}".format(i, f(i)) for i in range(n)))


w("""## std.simd (spec std.simd.1-9, ADR 1014): fixed-width lane vectors, 128 and
## 256 bits. GENERATED by tools/simd/gen.py: change the generator, not this file.
##
## A vector is a struct of its lanes. Every operation is defined lane by lane
## (std.simd.3), so a program means the same on every target, whatever width
## the machine's vector unit has.

## One `i32` mask lane: all ones when `c`, else zero (std.simd.7).
fn mask32(c bool) i32
    if c
        return (0 - 1).to_i32()
    0.to_i32()

## One `int` mask lane: all ones when `c`, else zero (std.simd.7).
fn mask64(c bool) int
    if c
        return 0 - 1
    0

## `v` wrapped to 32 bits, two's complement.
fn wrap32(v int) i32
    ((v + 2147483648).bit_and(4294967295) - 2147483648).to_i32()

## The smaller of two lanes (std.simd.5): a NaN if either is one, and `-0.0`
## for `-0.0` and `0.0`.
fn min32(a f32, b f32) f32
    if a != a
        return a
    if b != b
        return b
    if a < b
        return a
    if b < a
        return b
    if a == 0.0 and 1.0 / a < 0.0
        return a
    b

fn max32(a f32, b f32) f32
    if a != a
        return a
    if b != b
        return b
    if a > b
        return a
    if b > a
        return b
    if a == 0.0 and 1.0 / a > 0.0
        return a
    b

fn min64(a float, b float) float
    if a != a
        return a
    if b != b
        return b
    if a < b
        return a
    if b < a
        return b
    if a == 0.0 and 1.0 / a < 0.0
        return a
    b

fn max64(a float, b float) float
    if a != a
        return a
    if b != b
        return b
    if a > b
        return a
    if b > a
        return b
    if a == 0.0 and 1.0 / a > 0.0
        return a
    b

## Traps with `std.simd.2` unless `n` is a lane number below `lanes`.
fn check_lane(n int, lanes int)
    if n < 0 or n >= lanes
        unreachable("std.simd.2: lane {n} is out of range for a vector of {lanes} lanes")

## Traps with `std.simd.6` unless `n` is a shift count below `bits`.
fn check_shift(n int, bits int)
    if n < 0 or n >= bits
        unreachable("std.simd.6: shift count {n} is out of range 0..{bits}")
""")

for (name, e, n, mask, kind) in TYPES:
    isf = kind in ("f32", "f64")
    bits = {"f32": 32, "f64": 64, "i32": 32, "i64": 64}[kind]
    zero = "0.0" if isf else "0"
    if kind == "i32":
        zero = "0.to_i32()"
    mk = "mask32" if mask.startswith("I32") else "mask64"
    w("")
    w("## {} lanes of `{}` ({} bits).".format(n, e, n * bits))
    w("pub struct {}".format(name))
    for i in range(n):
        w("    l{} {}".format(i, e))
    w("")
    w("## Every lane `x` (std.simd.1).")
    w("pub fn {}.splat(x {}) {}".format(name, e, name))
    w("    " + build(name, n, lambda i: "x"))
    w("")
    w("## Every lane zero (std.simd.1).")
    w("pub fn {}.zero() {}".format(name, name))
    w("    " + build(name, n, lambda i: zero))
    w("")
    w("## The lanes `xs[at]` to `xs[at + {}]` (std.simd.1).".format(n - 1))
    w("pub fn {}.load(xs List[{}], at int) {}".format(name, e, name))
    w("    " + build(name, n, lambda i: "xs[at]" if i == 0 else "xs[at + {}]".format(i)))
    w("")
    w("## The lanes as a list (std.simd.1).")
    w("pub fn {}.to_list(self) List[{}]".format(name, e))
    w("    [{}]".format(", ".join("l{}".format(i) for i in range(n))))
    w("")
    w("## Write the lanes to `xs[at]` to `xs[at + {}]` (std.simd.1).".format(n - 1))
    w("pub fn {}.store(self, mut xs List[{}], at int)".format(name, e))
    for i in range(n):
        w("    xs[{}] = l{}".format("at" if i == 0 else "at + {}".format(i), i))
    w("")
    w("## Lane `i` (std.simd.2).")
    w("pub fn {}.lane(self, i int) {}".format(name, e))
    w("    check_lane(i, {})".format(n))
    w("    to_list()[i]")
    w("")
    w("## A copy with lane `i` set to `x` (std.simd.2).")
    w("pub fn {}.with_lane(self, i int, x {}) {}".format(name, e, name))
    w("    check_lane(i, {})".format(n))
    w("    mut xs := to_list()")
    w("    xs[i] = x")
    w("    {}.load(xs, 0)".format(name))

    def bin_(meth, doc, f):
        w("")
        w("## {}".format(doc))
        w("pub fn {}.{}(self, o {}) {}".format(name, meth, name, name))
        w("    " + build(name, n, f))

    if isf:
        bin_("add", "Lane-wise `a + b` (std.simd.4).", lambda i: "l{0} + o.l{0}".format(i))
        bin_("sub", "Lane-wise `a - b` (std.simd.4).", lambda i: "l{0} - o.l{0}".format(i))
        bin_("mul", "Lane-wise `a * b` (std.simd.4).", lambda i: "l{0} * o.l{0}".format(i))
        bin_("div", "Lane-wise `a / b` (std.simd.4).", lambda i: "l{0} / o.l{0}".format(i))
        mn = "min32" if kind == "f32" else "min64"
        mxn = "max32" if kind == "f32" else "max64"
        bin_("min", "Lane-wise minimum (std.simd.5).", lambda i: "{}(l{}, o.l{})".format(mn, i, i))
        bin_("max", "Lane-wise maximum (std.simd.5).", lambda i: "{}(l{}, o.l{})".format(mxn, i, i))
        w("")
        w("## Lane-wise square root, correctly rounded (std.simd.4).")
        w("pub fn {}.sqrt(self) {}".format(name, name))
        w("    " + build(name, n, lambda i: "l{}.sqrt()".format(i)))
        w("")
        w("## Lane-wise absolute value (std.simd.4).")
        w("pub fn {}.abs(self) {}".format(name, name))
        w("    " + build(name, n, lambda i: "l{}.abs()".format(i)))
        w("")
        w("## Lane-wise negation (std.simd.4).")
        w("pub fn {}.neg(self) {}".format(name, name))
        w("    " + build(name, n, lambda i: "-l{}".format(i)))
    else:
        bin_("add", "Lane-wise sum, wrapping (std.simd.4).", lambda i: "l{0}.wrapping_add(o.l{0})".format(i))
        bin_("sub", "Lane-wise difference, wrapping (std.simd.4).", lambda i: "l{0}.wrapping_sub(o.l{0})".format(i))
        if kind == "i32":
            bin_("mul", "Lane-wise product, wrapping (std.simd.4).", lambda i: "l{0}.wrapping_mul(o.l{0})".format(i))
            bin_("min", "Lane-wise minimum (std.simd.5).", lambda i: "l{0}.min(o.l{0})".format(i))
            bin_("max", "Lane-wise maximum (std.simd.5).", lambda i: "l{0}.max(o.l{0})".format(i))
        w("")
        w("## Lane-wise negation, wrapping (std.simd.4).")
        w("pub fn {}.neg(self) {}".format(name, name))
        w("    " + build(name, n, lambda i: "l{}.wrapping_neg()".format(i)))
        if kind == "i32":
            band = lambda a, b: "{}.to_int().bit_and({}.to_int()).to_i32()".format(a, b)
            bor = lambda a, b: "{}.to_int().bit_or({}.to_int()).to_i32()".format(a, b)
            bxor = lambda a, b: "{}.to_int().bit_xor({}.to_int()).to_i32()".format(a, b)
            bnot = lambda a: "{}.to_int().bit_not().to_i32()".format(a)
        else:
            band = lambda a, b: "{}.bit_and({})".format(a, b)
            bor = lambda a, b: "{}.bit_or({})".format(a, b)
            bxor = lambda a, b: "{}.bit_xor({})".format(a, b)
            bnot = lambda a: "{}.bit_not()".format(a)
        bin_("bit_and", "Lane-wise bitwise and (std.simd.6).", lambda i: band("l%d" % i, "o.l%d" % i))
        bin_("bit_or", "Lane-wise bitwise or (std.simd.6).", lambda i: bor("l%d" % i, "o.l%d" % i))
        bin_("bit_xor", "Lane-wise bitwise exclusive or (std.simd.6).", lambda i: bxor("l%d" % i, "o.l%d" % i))
        w("")
        w("## Lane-wise bitwise not (std.simd.6).")
        w("pub fn {}.bit_not(self) {}".format(name, name))
        w("    " + build(name, n, lambda i: bnot("l%d" % i)))
        w("")
        w("## Every lane shifted left by `k` bits, the bits that leave dropped (std.simd.6).")
        w("pub fn {}.shl(self, k int) {}".format(name, name))
        w("    check_shift(k, {})".format(bits))
        if kind == "i32":
            w("    " + build(name, n, lambda i: "wrap32(l{}.to_int().shl(k))".format(i)))
        else:
            w("    " + build(name, n, lambda i: "l{}.shl(k)".format(i)))
        w("")
        w("## Every lane shifted right by `k` bits, copying the sign bit (std.simd.6).")
        w("pub fn {}.shr(self, k int) {}".format(name, name))
        w("    check_shift(k, {})".format(bits))
        if kind == "i32":
            w("    " + build(name, n, lambda i: "l{}.to_int().shr(k).to_i32()".format(i)))
        else:
            w("    " + build(name, n, lambda i: "l{}.shr(k)".format(i)))

    # comparisons (std.simd.7)
    for meth, op in (("eq", "=="), ("ne", "!="), ("lt", "<"), ("le", "<="), ("gt", ">"), ("ge", ">=")):
        w("")
        w("## Lane-wise `a {} b`: all ones where it holds, else zero (std.simd.7).".format(op))
        w("pub fn {}.{}(self, o {}) {}".format(name, meth, name, mask))
        w("    " + build(mask, n, lambda i: "{}(l{} {} o.l{})".format(mk, i, op, i)))
    w("")
    w("## The lanes of `o` where `m` is not zero, else of this vector (std.simd.7).")
    w("pub fn {}.blend(self, o {}, m {}) {}".format(name, name, mask, name))
    w("    " + build(name, n, lambda i: "(if m.l{0} != {1} then o.l{0} else l{0})".format(
        i, "0.to_i32()" if mask.startswith("I32") else "0")))
    # horizontal sum, a fixed pairwise tree (std.simd.8)
    w("")
    w("## The sum of the lanes, added as a balanced tree: lanes 0 and 1, 2 and 3, and so on,")
    w("## then those sums in pairs (std.simd.8).")
    w("pub fn {}.sum(self) {}".format(name, e))
    add = (lambda a, b: "{} + {}".format(a, b)) if isf else (lambda a, b: "{}.wrapping_add({})".format(a, b))
    level = ["l{}".format(i) for i in range(n)]
    k = 0
    while len(level) > 1:
        nxt = []
        for j in range(0, len(level), 2):
            nm = "s{}".format(k)
            k += 1
            w("    {} := {}".format(nm, add(level[j], level[j + 1])))
            nxt.append(nm)
        level = nxt
    w("    {}".format(level[0]))

text = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).rstrip("\n")
print(text)
