//! Git dependencies and `ail.lock` (mod.pkg.6-9), ADRs 0355-0357.
//!
//! The toolchain fetches a `git` dependency with the system `git` into
//! `$AIL_HOME/deps/NAME-COMMIT` (`~/.ail/deps` without `AIL_HOME`): a plain,
//! read-only tree without `.git`, never updated in place (mod.pkg.7).
//! `ail.lock`, next to the root's `ail.pkg`, pins every git dependency of the
//! graph to a commit; a build uses the locked commit while the manifest line
//! still matches it (mod.pkg.8).

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Mutex;

use crate::diag::{Diagnostic, Pos};

/// The lockfile's name (mod.pkg.8).
pub const LOCK: &str = "ail.lock";

/// How the command that loads the program treats fetching and the lock.
#[derive(Clone, Default)]
pub struct Options {
    /// Write `ail.lock` when it is absent or stale (`ail run`, `ail test`).
    pub write_lock: bool,
    /// `--deterministic`: a stale lock is an error (mod.pkg.8).
    pub frozen: bool,
    /// `--deny net`: use only what the cache holds (mod.pkg.7).
    pub offline: bool,
    /// `ail pkg update`: these dependencies (all if empty) ignore the lock
    /// (mod.pkg.9).
    pub refresh: Option<Vec<String>>,
}

static OPTIONS: Mutex<Option<Options>> = Mutex::new(None);

/// Set the options for the program the command loads.
pub fn configure(o: Options) {
    *OPTIONS.lock().unwrap_or_else(|e| e.into_inner()) = Some(o);
}

pub fn options() -> Options {
    OPTIONS.lock().unwrap_or_else(|e| e.into_inner()).clone().unwrap_or_default()
}

/// A `git` dependency's source: `git URL` and its `rev` or `tag` pin.
#[derive(Clone, PartialEq)]
pub struct Source {
    pub url: String,
    /// `"rev"` or `"tag"`.
    pub kind: &'static str,
    pub pin: String,
}

/// One `ail.lock` line: `dep NAME git URL rev|tag PIN commit SHA`.
#[derive(Clone, PartialEq)]
pub struct Entry {
    pub name: String,
    pub source: Source,
    pub commit: String,
}

impl Entry {
    fn line(&self) -> String {
        let s = &self.source;
        format!("dep {} git {} {} {} commit {}\n", self.name, quote(&s.url), s.kind, quote(&s.pin), self.commit)
    }
}

fn quote(w: &str) -> String {
    if w.is_empty() || w.contains(|c: char| c.is_whitespace() || c == '#' || c == '"') {
        format!("\"{w}\"")
    } else {
        w.to_string()
    }
}

/// The lock as read, and the entries this load used.
#[derive(Default)]
pub struct Lock {
    path: PathBuf,
    present: bool,
    text: String,
    entries: Vec<Entry>,
    pub used: Vec<Entry>,
    /// A fetch failed, so the lock isn't rewritten.
    pub failed: bool,
}

impl Lock {
    /// Read `ail.lock` in `root`. A malformed line is ignored: the lock is
    /// generated, so it is then stale and rewritten.
    pub fn read(root: &Path) -> Lock {
        let path = root.join(LOCK);
        let Ok(text) = std::fs::read_to_string(&path) else { return Lock { path, ..Lock::default() } };
        let mut entries = Vec::new();
        for (i, line) in text.lines().enumerate() {
            let ws: Vec<String> = super::words(line, i + 1, &mut Vec::new()).into_iter().map(|(w, _)| w).collect();
            if let [dep, name, git, url, kind, pin, commit, sha] = ws.as_slice()
                && dep == "dep"
                && git == "git"
                && commit == "commit"
                && let Some(kind) = ["rev", "tag"].into_iter().find(|k| k == kind)
            {
                entries.push(Entry {
                    name: name.clone(),
                    source: Source { url: url.clone(), kind, pin: pin.clone() },
                    commit: sha.clone(),
                });
            }
        }
        Lock { path, present: true, text, entries, ..Lock::default() }
    }

    /// The locked commit of dependency `name`, if its entry matches
    /// `source` and `ail pkg update` isn't refreshing it.
    pub fn locked(&self, name: &str, source: &Source, refresh: &Option<Vec<String>>) -> Option<&str> {
        if refresh.as_ref().is_some_and(|r| r.is_empty() || r.iter().any(|n| n == name)) {
            return None;
        }
        self.entries.iter().find(|e| e.name == name && e.source == *source).map(|e| e.commit.as_str())
    }

    fn render(&self) -> String {
        let mut used = self.used.clone();
        used.sort_by(|a, b| a.name.cmp(&b.name));
        let mut s = String::from("# Generated by `ail`; commit it. `ail pkg update NAME` refreshes an entry (mod.pkg.8-9).\n");
        for e in &used {
            s.push_str(&e.line());
        }
        s
    }

    /// Is the lock out of step with the manifests (mod.pkg.8)?
    pub fn stale(&self) -> bool {
        if !self.present {
            return !self.used.is_empty();
        }
        self.render() != self.text
    }

    /// Entries for dependencies that no manifest declares any more.
    pub fn extra(&self) -> Vec<&str> {
        let mut out: Vec<&str> =
            self.entries.iter().filter(|e| !self.used.iter().any(|u| u.name == e.name)).map(|e| e.name.as_str()).collect();
        out.sort_unstable();
        out
    }

    /// Write the lock if it is stale and every fetch succeeded.
    pub fn save(&self) -> Result<bool, String> {
        if self.failed || !self.stale() {
            return Ok(false);
        }
        std::fs::write(&self.path, self.render()).map_err(|e| format!("can't write {}: {e}", crate::shown::shown(&self.path)))?;
        Ok(true)
    }
}

/// `$AIL_HOME`, else `~/.ail` (mod.pkg.7).
pub fn home() -> PathBuf {
    if let Some(h) = std::env::var_os("AIL_HOME").filter(|h| !h.is_empty()) {
        return PathBuf::from(h);
    }
    let user = std::env::var_os("HOME").or_else(|| std::env::var_os("USERPROFILE")).unwrap_or_default();
    PathBuf::from(user).join(".ail")
}

/// Fetch dependency `name` from `source`, at `locked` if the lock pins it,
/// and return its commit and directory, or a mod.pkg.7 diagnostic at `pos`.
pub fn fetch(name: &str, source: &Source, locked: Option<&str>, offline: bool, pos: Pos) -> Result<(String, PathBuf), Diagnostic> {
    let deps = home().join("deps");
    if let Some(c) = locked {
        let dir = deps.join(format!("{name}-{c}"));
        if dir.is_dir() {
            return Ok((c.to_string(), dir));
        }
    }
    let err = |msg: String, help: &str| Err(Diagnostic::new("mod.pkg.7", pos, msg).help(help.to_string()));
    if offline {
        return err(
            format!("dependency `{name}` isn't in the cache `{}`, and `--deny net` refuses to fetch it", crate::shown::shown(&deps)),
            "run the program once without `--deny net` or `--deterministic` to fetch it",
        );
    }
    if let Err(e) = std::fs::create_dir_all(&deps) {
        return err(format!("can't create the cache `{}` for dependency `{name}`: {e}", crate::shown::shown(&deps)), "set `AIL_HOME` to a writable directory");
    }
    let stamp = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_nanos());
    let tmp = deps.join(format!(".fetch-{name}-{}-{stamp}", std::process::id()));
    let result = clone(name, source, locked, &tmp, &deps);
    if tmp.exists() {
        let _ = std::fs::remove_dir_all(&tmp);
    }
    result.map_err(|(msg, help)| Diagnostic::new("mod.pkg.7", pos, msg).help(help))
}

fn git(args: &[&str], dir: Option<&Path>) -> Result<std::process::Output, std::io::Error> {
    let mut c = Command::new("git");
    if let Some(d) = dir {
        c.current_dir(d);
    }
    // Never wait on a password prompt.
    c.args(args).env("GIT_TERMINAL_PROMPT", "0").output()
}

fn clone(name: &str, source: &Source, locked: Option<&str>, tmp: &Path, deps: &Path) -> Result<(String, PathBuf), (String, String)> {
    let tmp_s = tmp.display().to_string();
    let out = git(&["clone", "--quiet", "--no-checkout", &source.url, &tmp_s], None).map_err(|e| {
        (format!("can't run `git` to fetch dependency `{name}`: {e}"), "install `git`, or depend on a local copy with `path DIR`".to_string())
    })?;
    if !out.status.success() {
        let why = String::from_utf8_lossy(&out.stderr);
        let why = why.lines().find(|l| !l.trim().is_empty()).unwrap_or("git failed").trim();
        return Err((
            format!("can't fetch dependency `{name}` from `{}`: {why}", source.url),
            "check the URL and the network; a repository that needs a password needs `git` credentials".to_string(),
        ));
    }
    let want = match (locked, source.kind) {
        (Some(c), _) => c.to_string(),
        (None, "tag") => format!("refs/tags/{}", source.pin),
        (None, _) => source.pin.clone(),
    };
    let out = git(&["rev-parse", "--verify", "--quiet", &format!("{want}^{{commit}}")], Some(tmp))
        .map_err(|e| (format!("can't run `git` for dependency `{name}`: {e}"), "install `git`".to_string()))?;
    if !out.status.success() {
        let what = match locked {
            Some(c) => format!("the locked commit `{c}`"),
            None => format!("{} `{}`", source.kind, source.pin),
        };
        let help = if locked.is_some() {
            format!("`ail pkg update {name}` locks what the manifest names now")
        } else {
            format!("pin a {} that `{}` has", source.kind, source.url)
        };
        return Err((format!("dependency `{name}`: `{}` has no {what}", source.url), help));
    }
    let commit = String::from_utf8_lossy(&out.stdout).trim().to_string();
    let out = git(&["-c", "advice.detachedHead=false", "checkout", "--quiet", "--detach", &commit], Some(tmp))
        .map_err(|e| (format!("can't run `git` for dependency `{name}`: {e}"), "install `git`".to_string()))?;
    if !out.status.success() {
        return Err((format!("can't check out commit `{commit}` of dependency `{name}`"), "try again; the cache may be out of space".to_string()));
    }
    let _ = std::fs::remove_dir_all(tmp.join(".git"));
    let dir = deps.join(format!("{name}-{commit}"));
    // Another process may have fetched it meanwhile; its tree is the same.
    if !dir.exists() {
        std::fs::rename(tmp, &dir)
            .map_err(|e| (format!("can't move dependency `{name}` into the cache: {e}"), "set `AIL_HOME` to a writable directory".to_string()))?;
        read_only(&dir);
    }
    Ok((commit, dir))
}

/// Make the files under `dir` read-only (mod.pkg.7). Directories stay
/// writable so the cache can be cleared.
fn read_only(dir: &Path) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            read_only(&p);
        } else if let Ok(meta) = std::fs::metadata(&p) {
            let mut perm = meta.permissions();
            perm.set_readonly(true);
            let _ = std::fs::set_permissions(&p, perm);
        }
    }
}
